/*
 * G-16 — one-shot harness to extract LDPC-encoded reference codewords from
 * LANS-AFS-SIM. Run once, copy the hex output into
 * cpp/tests/encoding/ldpc_lans_reference.hpp. Never needs to run in CI: the
 * constants it produces are pinned in the test header and the LDPC codebook
 * is fixed by the LSIS spec, so regeneration is only required if either
 * LANS-AFS-SIM's `encode_LDPC_AFS_SF2/SF3` or LunaLink's spec-defined
 * message format changes (neither is expected).
 *
 * Inputs: hard-coded — we feed the pure LDPC encoder directly with a known
 * 1200-bit / 870-bit message, skipping CRC24 so the test is not entangled
 * with the CRC endianness convention.
 *
 * Usage: dump_lans_ldpc
 *   Writes hex bytes of the 2400-bit SF2 codeword and 1740-bit SF3 codeword
 *   (both for all-zeros input) to stdout in C array initialiser format.
 */

#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "afs_nav.h"

static void print_bits_as_uint8_array(const char* name,
                                      const uint8_t* bits,
                                      size_t n_bits) {
    printf("inline constexpr std::array<uint8_t, %zu> %s = {\n    ",
           n_bits, name);
    for (size_t i = 0; i < n_bits; ++i) {
        printf("%u", (unsigned)(bits[i] & 1U));
        if (i + 1 < n_bits) {
            printf(", ");
        }
        if ((i + 1) % 32 == 0 && i + 1 < n_bits) {
            printf("\n    ");
        }
    }
    printf("\n};\n\n");
}

int main(void) {
    /* SF2: 1200 info bits (1176 data + 24 CRC slot) → 2400 coded bits. */
    uint8_t sf2_info[1200];
    uint8_t sf2_coded[2400];
    memset(sf2_info, 0, sizeof(sf2_info));

    /* Deterministic non-trivial pattern: alternating bits in the data
     * region, zero CRC slot. Choosing non-zero data forces a non-trivial
     * codeword — all-zeros input would encode to all-zeros for any
     * systematic linear code and miss sign/parity bugs. */
    for (size_t i = 0; i < 1176; ++i) {
        sf2_info[i] = (uint8_t)(i & 1U);
    }
    /* sf2_info[1176..1199] already zero (no CRC, deliberate). */

    encode_LDPC_AFS_SF2(sf2_info, sf2_coded);

    /* SF3: 870 info bits (846 data + 24 CRC slot) → 1740 coded bits. */
    uint8_t sf3_info[870];
    uint8_t sf3_coded[1740];
    memset(sf3_info, 0, sizeof(sf3_info));
    for (size_t i = 0; i < 846; ++i) {
        sf3_info[i] = (uint8_t)((i >> 1) & 1U);  /* 0,0,1,1,0,0,1,1,... */
    }

    encode_LDPC_AFS_SF3(sf3_info, sf3_coded);

    printf("// Generated by scripts/interop/dump_lans_ldpc.c — G-16.\n"
           "// Regenerate: python scripts/interop/build_lans_afs_sim.py &&\n"
           "//   third_party/LANS-AFS-SIM/dump_lans_ldpc > \\\n"
           "//   cpp/tests/encoding/ldpc_lans_reference.hpp\n"
           "// (with the file header + namespace wrapping added by hand.)\n\n");

    printf("// Input for SF2: data[i] = i & 1, CRC slot zero.\n");
    print_bits_as_uint8_array("kLansSf2AltInput", sf2_info, 1200);

    printf("// Reference SF2 codeword from LANS-AFS-SIM encode_LDPC_AFS_SF2.\n");
    print_bits_as_uint8_array("kLansSf2AltCoded", sf2_coded, 2400);

    printf("// Input for SF3: data[i] = (i>>1) & 1, CRC slot zero.\n");
    print_bits_as_uint8_array("kLansSf3AltInput", sf3_info, 870);

    printf("// Reference SF3 codeword from LANS-AFS-SIM encode_LDPC_AFS_SF3.\n");
    print_bits_as_uint8_array("kLansSf3AltCoded", sf3_coded, 1740);

    return 0;
}
